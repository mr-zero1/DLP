"""Service/cache boundary for a future asynchronous adapter.

The UI observes cached records through ``changed``. A real adapter must fetch in
workers, then replace cached DTOs and emit on the Qt UI thread. Deployment jobs
will move to the independent server; the current controller is demo-only.
"""
from typing import Protocol
from app.models.entities import Endpoint, Incident, Policy, Rule, AuditEvent, EnrollmentToken, Release

class ChangeNotification(Protocol):
    def connect(self, callback): ...
    def emit(self): ...

class ControlService(Protocol):
    changed: ChangeNotification
    endpoints: list[Endpoint]
    incidents: list[Incident]
    policies: list[Policy]
    rules: list[Rule]
    audit: list[AuditEvent]
    tokens: list[EnrollmentToken]
    releases: list[Release]
    deployments: list[dict]
    settings: dict
    def endpoint(self, id: str) -> Endpoint: ...
    def incident(self, id: str) -> Incident: ...
    def policy(self, id: str) -> Policy: ...
    def rule(self, id: str) -> Rule: ...
    def stats(self) -> dict: ...
    def save_policy(self, policy: Policy, publish: bool = False) -> None: ...
    def save_rule(self, rule: Rule) -> None: ...
    def update_incident(self, incident_id: str, status: str, note: str) -> None: ...
    def assign_policy(self, endpoint_id: str, policy_id: str) -> None: ...
    def sync(self, endpoint_id: str) -> None: ...
    def create_token(self, name: str, group: str, policy_id: str, hours: int, uses: int) -> tuple[EnrollmentToken,str]: ...
    def revoke_token(self, id: str) -> None: ...
    def save_settings(self, values: dict) -> None: ...
    def log(self, action, resource, before=None, after=None, result='Success', actor='Ameer Ahmed') -> AuditEvent: ...
    def reset(self) -> None: ...
